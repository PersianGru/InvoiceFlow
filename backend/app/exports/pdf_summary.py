"""A one-page PDF summary of an invoice (header, parties, totals, lines, validation) for files and
e-mails where the canonical JSON is too much. Built with fpdf2; Latin-1 safe text."""

from __future__ import annotations

import unicodedata
from decimal import Decimal
from typing import Any

from app.schemas.invoice import Invoice


def _latin1(text: str) -> str:
    out = unicodedata.normalize("NFKD", text).encode("latin-1", "ignore").decode("latin-1")
    return out.replace("€", "EUR")


def _money(v: Decimal | None, currency: str | None) -> str:
    if v is None:
        return "-"
    return f"{v.quantize(Decimal('0.01'))} {currency or ''}".strip()


def render_pdf_summary(invoice: Invoice, extra: dict[str, Any] | None = None) -> bytes:
    from fpdf import FPDF

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 15)
    title = f"{invoice.document_type.value.replace('_', ' ').title()} {invoice.number or ''}".strip()
    pdf.cell(0, 10, _latin1(title), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=10)

    def line(label: str, value: Any) -> None:
        if value in (None, "", []):
            return
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(45, 6, _latin1(label))
        pdf.set_font("Helvetica", size=10)
        pdf.cell(0, 6, _latin1(str(value)), new_x="LMARGIN", new_y="NEXT")

    line("Issue date", invoice.issue_date)
    line("Due date", invoice.payment.due_date)
    line("Supplier", invoice.supplier.name)
    line("Supplier VAT id", invoice.supplier.vat_id)
    line("Supplier IBAN", invoice.supplier.iban)
    line("Buyer", invoice.buyer.name)
    line("Buyer VAT id", invoice.buyer.vat_id)
    line("Currency", invoice.currency)
    line("Net total", _money(invoice.totals.net_total, invoice.currency))
    line("VAT total", _money(invoice.totals.vat_total, invoice.currency))
    line("Gross total", _money(invoice.totals.gross_total, invoice.currency))
    line("Payment reference", invoice.payment.payment_reference)
    line("Purchase order", invoice.references.purchase_order)
    line("Review status", invoice.review_status.value)
    for k, v in (extra or {}).items():
        line(k, v)
    if invoice.lines:
        pdf.ln(3)
        pdf.set_font("Helvetica", "B", 10)
        for w, h in ((90, "Description"), (20, "Qty"), (30, "Unit price"), (30, "Net"), (20, "VAT %")):
            pdf.cell(w, 6, h, border="B")
        pdf.ln(6)
        pdf.set_font("Helvetica", size=9)
        for ln in invoice.lines[:60]:
            pdf.cell(90, 6, _latin1((ln.description or "")[:60]))
            pdf.cell(20, 6, f"{ln.quantity or ''}")
            pdf.cell(30, 6, f"{ln.unit_price if ln.unit_price is not None else ''}")
            pdf.cell(30, 6, f"{ln.net_amount if ln.net_amount is not None else ''}")
            pdf.cell(
                20, 6, f"{ln.vat_rate if ln.vat_rate is not None else ''}", new_x="LMARGIN", new_y="NEXT"
            )
    if invoice.validation:
        pdf.ln(3)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 6, "Checks", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", size=9)
        for v in invoice.validation[:40]:
            pdf.multi_cell(0, 5, _latin1(f"[{v.level.value}] {v.reason}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "I", 8)
    pdf.ln(4)
    pdf.cell(0, 5, _latin1(f"Generated by InvoiceFlow from the canonical record {invoice.id}"))
    return bytes(pdf.output())
