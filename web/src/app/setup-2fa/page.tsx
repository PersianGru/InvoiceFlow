"use client";
// Mandatory 2FA: scan the QR code, confirm one code, save the ten recovery codes.
import { useRouter } from "next/navigation";
import { useEffect, useState, type FormEvent } from "react";

import { Button, Card, Field, Input, Notice, Spinner } from "@/components/ui";
import { ApiError, post } from "@/lib/api";
import { useApp } from "@/lib/app-context";
import { homeFor } from "@/lib/countries";

interface Setup {
  otpauth_uri: string;
  secret: string;
  qr_svg: string;
}

export default function SetupTwoFactorPage() {
  const { t, ready, user, refreshSession } = useApp();
  const router = useRouter();
  const [setup, setSetup] = useState<Setup | null>(null);
  const [code, setCode] = useState("");
  const [codes, setCodes] = useState<string[] | null>(null);
  const [saved, setSaved] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    if (!ready) return;
    if (!user) {
      router.replace("/login");
      return;
    }
    if (user.totp_enabled && !codes) {
      router.replace(homeFor({ ...user, mfa_setup_required: false }));
      return;
    }
    if (!setup && !codes) {
      void post<Setup>("/api/v1/users/me/totp/setup")
        .then(setSetup)
        .catch((e) => setError(e instanceof ApiError ? e.message : t("common.error")));
    }
  }, [ready, user, setup, codes, router, t]);

  async function confirm(e: FormEvent) {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      const r = await post<{ recovery_codes: string[] }>("/api/v1/users/me/totp/confirm", { code: code.replace(/\s/g, "") });
      setCodes(r.recovery_codes);
    } catch (err) {
      setError(err instanceof ApiError ? err.message : t("common.error"));
    } finally {
      setBusy(false);
    }
  }

  async function done() {
    await refreshSession();
    if (user) router.replace(homeFor({ ...user, mfa_setup_required: false }));
  }

  function download() {
    const blob = new Blob([`InvoiceFlow recovery codes for ${user?.email ?? ""}\n\n${(codes ?? []).join("\n")}\n`], { type: "text/plain" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "invoiceflow-recovery-codes.txt";
    a.click();
    URL.revokeObjectURL(a.href);
  }

  return (
    <main className="mx-auto w-full max-w-lg flex-1 px-4 py-10">
      <h1 className="mb-2 text-2xl font-semibold">{t("mfa.title")}</h1>
      <p className="mb-4 text-sm text-neutral-600 dark:text-neutral-400">{t("mfa.intro")}</p>
      {error ? (
        <Notice tone="danger" role="alert" className="mb-3">
          {error}
        </Notice>
      ) : null}
      {codes ? (
        <Card title={t("mfa.codes_title")}>
          <p className="mb-3 text-sm">{t("mfa.codes_intro")}</p>
          <ul className="mb-3 grid grid-cols-2 gap-1 font-mono text-sm">
            {codes.map((c) => (
              <li key={c} className="rounded bg-neutral-100 px-2 py-1 dark:bg-neutral-800">
                {c}
              </li>
            ))}
          </ul>
          <div className="mb-3 flex gap-2">
            <Button variant="secondary" size="sm" onClick={download}>
              {t("mfa.download")}
            </Button>
            <Button variant="secondary" size="sm" onClick={() => void navigator.clipboard?.writeText(codes.join("\n"))}>
              {t("common.copy")}
            </Button>
          </div>
          <label className="mb-3 flex items-center gap-2 text-sm">
            <input type="checkbox" checked={saved} onChange={(e) => setSaved(e.target.checked)} />
            {t("mfa.saved")}
          </label>
          <Button disabled={!saved} onClick={() => void done()}>
            {t("mfa.continue")}
          </Button>
        </Card>
      ) : setup ? (
        <Card>
          <ol className="mb-3 list-decimal space-y-1 pl-5 text-sm">
            <li>{t("mfa.step1")}</li>
            <li>{t("mfa.step2")}</li>
          </ol>
          {/* the SVG is generated by our API from the otpauth URI; it contains no script */}
          <div className="mx-auto mb-3 w-56 rounded bg-white p-2" aria-label={t("mfa.qr")} role="img" dangerouslySetInnerHTML={{ __html: setup.qr_svg }} />
          <details className="mb-3 text-sm">
            <summary className="cursor-pointer">{t("mfa.manual")}</summary>
            <code className="mt-1 block break-all rounded bg-neutral-100 px-2 py-1 dark:bg-neutral-800">{setup.secret}</code>
          </details>
          <form onSubmit={confirm}>
            <Field id="code" label={t("login.totp")}>
              <Input id="code" inputMode="numeric" autoComplete="one-time-code" required value={code} onChange={(e) => setCode(e.target.value)} />
            </Field>
            <Button type="submit" disabled={busy || code.replace(/\s/g, "").length < 6}>
              {t("mfa.confirm")}
            </Button>
          </form>
        </Card>
      ) : (
        <Spinner label={t("common.loading")} />
      )}
    </main>
  );
}
